package com.immoral.location.ui

import com.immoral.location.ui.components.FavoriteText
import org.junit.Assert.assertEquals
import org.junit.Test

/**
 * Locks the display-side naming of saved places.
 *
 * `FavoritesStore` stores the placeholder `收藏地点 N` for a place saved without a name. The saved
 * places *screen* is titled 已保存的地点, but the peek card's entry chip and the list rows must not
 * repeat the old heading — the acceptance check `11-favorites` locates a row by its coordinate text
 * and the tools panel announced the section as `收藏地点 · 共 N 个收藏`, so a row that also started
 * with 收藏地点 made label and row indistinguishable. Hence the mapping is explicit and tested.
 */
class FavoriteTextTest {

    @Test
    fun autoGeneratedNamesBecomeTheNewCopy() {
        assertEquals("收藏点 1", FavoriteText.displayName("收藏地点 1"))
        assertEquals("收藏点 12", FavoriteText.displayName("收藏地点 12"))
        // surrounding whitespace comes from renames, not from the store
        assertEquals("收藏点 3", FavoriteText.displayName("  收藏地点 3 "))
    }

    @Test
    fun userNamesAreUntouched() {
        assertEquals("公司", FavoriteText.displayName("公司"))
        assertEquals("39.9087, 116.3975", FavoriteText.displayName("39.9087, 116.3975"))
        // a name that merely *contains* the placeholder text is a user choice: keep it
        assertEquals("收藏地点附近", FavoriteText.displayName("收藏地点附近"))
        assertEquals("我的收藏地点", FavoriteText.displayName("我的收藏地点"))
    }

    @Test
    fun blankNamesStillRenderSomething() {
        assertEquals("收藏点", FavoriteText.displayName(""))
        assertEquals("收藏点", FavoriteText.displayName("   "))
    }
}
